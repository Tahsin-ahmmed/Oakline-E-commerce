/** Colour × size grid with a deterministic, varied stock pattern (some low / sold-out sizes). */
function grid(colors: { name: string; hex: string }[], sizes: string[], base = 8): SeedVariant[] {
  const out: SeedVariant[] = [];
  colors.forEach((c, ci) =>
    sizes.forEach((s, si) => {
      const pattern = [base, base + 4, base + 2, Math.max(0, base - 5), base - 6 > 0 ? base - 6 : 0];
      out.push({ color: c.name, colorHex: c.hex, size: s, stock: pattern[(si + ci) % pattern.length] });
    }),
  );
  return out;
}
const sizesOnly = (sizes: string[], base = 6): SeedVariant[] =>
  sizes.map((s, i) => ({ size: s, stock: [base, base + 3, base + 1, 2, base - 2][i % 5] }));

